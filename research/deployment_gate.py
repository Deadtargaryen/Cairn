#!/usr/bin/env python3
"""Create a conservative deployment-gate report from research artifacts.

The gate is intentionally fail-closed. It does not promote a strategy or
authorize exchange access; it records why the current evidence is or is not
sufficient for the next research stage.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
import uuid
from pathlib import Path
from typing import Any


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def current_hash(project_root: Path, relative_path: str) -> str:
    return sha256((project_root / relative_path).resolve())


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--warehouse", type=Path, required=True)
    parser.add_argument("--baseline", type=Path, required=True)
    parser.add_argument("--analysis", type=Path, required=True)
    parser.add_argument("--walk-forward", type=Path, required=True)
    parser.add_argument("--viability", type=Path, required=True)
    parser.add_argument("--risk-review", type=Path, required=True)
    parser.add_argument("--signal-diagnostics", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    return parser.parse_args()


def run(args: argparse.Namespace) -> dict[str, Any]:
    warehouse = args.warehouse.expanduser().resolve()
    baseline_path = args.baseline.expanduser().resolve()
    analysis_path = args.analysis.expanduser().resolve()
    walk_forward_path = args.walk_forward.expanduser().resolve()
    viability_path = args.viability.expanduser().resolve()
    risk_review_path = args.risk_review.expanduser().resolve()
    signal_diagnostics_path = args.signal_diagnostics.expanduser().resolve()
    baseline = load(baseline_path)
    analysis = load(analysis_path)
    walk_forward = load(walk_forward_path)
    viability = load(viability_path)
    risk_review = load(risk_review_path)
    signal_diagnostics = load(signal_diagnostics_path)
    project_root = Path(__file__).resolve().parents[1]

    reasons: list[str] = []
    blockers: list[str] = []
    checks: dict[str, Any] = {}

    checks["warehouse_exists"] = warehouse.is_file()
    checks["baseline_exists"] = baseline_path.is_file()
    checks["analysis_exists"] = analysis_path.is_file()
    checks["walk_forward_exists"] = walk_forward_path.is_file()
    checks["viability_exists"] = viability_path.is_file()
    checks["risk_review_exists"] = risk_review_path.is_file()
    checks["signal_diagnostics_exists"] = signal_diagnostics_path.is_file()
    if not all(checks.values()):
        blockers.append("required research artifact is missing")

    checks["baseline_reports"] = len(baseline.get("reports", []))
    checks["baseline_trade_count"] = baseline.get("trade_count", 0)
    checks["future_data_used_for_signal"] = baseline.get("features", {}).get("future_data_used_for_signal")
    if checks["future_data_used_for_signal"] is not False:
        blockers.append("future-data usage is not explicitly false")

    current_baseline_code_hash = current_hash(project_root, "research/backtest_baselines.py")
    current_assumptions_hash = current_hash(project_root, "research/research_assumptions.json")
    current_knowledge_base_hash = current_hash(project_root, "research/knowledge_base_references.json")
    baseline_spec = baseline.get("experiment_spec", {})
    checks["baseline_code_hash_current"] = current_baseline_code_hash
    checks["baseline_code_hash_match"] = baseline_spec.get("code_sha256") == current_baseline_code_hash
    checks["baseline_assumptions_hash_match"] = baseline_spec.get("assumptions_sha256") == current_assumptions_hash
    checks["baseline_knowledge_base_hash_match"] = baseline_spec.get("knowledge_base_sha256") == current_knowledge_base_hash
    if not checks["baseline_code_hash_match"]:
        blockers.append("baseline report was generated by a stale simulator code revision")
    if not checks["baseline_assumptions_hash_match"] or not checks["baseline_knowledge_base_hash_match"]:
        blockers.append("baseline report provenance hashes do not match current source registries")

    walk_spec = walk_forward.get("experiment_spec", {})
    current_walk_code_hash = current_hash(project_root, "research/walk_forward_baselines.py")
    checks["walk_forward_code_hash_match"] = walk_spec.get("code_sha256") == current_walk_code_hash
    checks["walk_forward_warehouse_hash_match"] = walk_spec.get("warehouse_sha256") == sha256(warehouse)
    checks["walk_forward_assumptions_hash_match"] = walk_forward.get("assumptions_sha256") == current_assumptions_hash
    checks["walk_forward_knowledge_base_hash_match"] = walk_forward.get("knowledge_base_sha256") == current_knowledge_base_hash
    if not all(
        checks[key]
        for key in (
            "walk_forward_code_hash_match",
            "walk_forward_warehouse_hash_match",
            "walk_forward_assumptions_hash_match",
            "walk_forward_knowledge_base_hash_match",
        )
    ):
        blockers.append("walk-forward report provenance hashes do not match current inputs")

    non_abstaining_walk_forward = [
        report for report in walk_forward.get("reports", []) if report.get("selected_strategy") != "no_trade"
    ]
    losing_selected_tests = [
        report for report in non_abstaining_walk_forward if float(report.get("test", {}).get("net_return", 0.0)) <= 0
    ]
    checks["walk_forward_fold_count"] = len(walk_forward.get("reports", []))
    checks["walk_forward_non_abstaining_count"] = len(non_abstaining_walk_forward)
    checks["walk_forward_nonpositive_selected_tests"] = len(losing_selected_tests)
    if losing_selected_tests:
        blockers.append("selected walk-forward strategies were non-positive on unseen test windows")
    if not non_abstaining_walk_forward:
        reasons.append("walk-forward selection predominantly chose NO_TRADE")

    passing_candidates = []
    for input_report in analysis.get("input_reports", []):
        passing_candidates.extend(input_report.get("descriptive_gate_passes", []))
    checks["descriptive_candidates"] = len(passing_candidates)
    if not passing_candidates:
        blockers.append("no non-abstaining strategy passed the descriptive out-of-sample gate")
    else:
        # A candidate can still be rejected below if it only survives one
        # cost scenario or is actually the random baseline.
        non_random = [candidate for candidate in passing_candidates if candidate.get("strategy") != "random_entry"]
        checks["non_random_descriptive_candidates"] = len(non_random)
        if not non_random:
            blockers.append("only random-entry behavior passed descriptive filters")

    checks["account_viability_decision"] = viability.get("decision")
    checks["minimum_notional_feasible"] = viability.get("derived", {}).get("minimum_notional_feasible")
    if viability.get("decision") == "DO_NOT_TRADE_LIVE":
        blockers.append("small-account viability gate explicitly blocks live trading")

    checks["risk_review_candidate_count"] = risk_review.get("candidate_count", 0)
    checks["risk_review_decision"] = risk_review.get("decision")
    if risk_review.get("decision") != "NO_DEPLOYMENT_CANDIDATE":
        blockers.append("risk review did not produce a clean no-candidate result")
    if any(
        report.get("risk_estimate_status") == "insufficient_sample"
        for report in risk_review.get("reports", [])
    ):
        reasons.append("some risk-of-ruin slices have insufficient out-of-sample trades for estimation")

    corrected_significant = [
        row
        for row in signal_diagnostics.get("conditional_results", [])
        if row.get("significant_bh_alpha_005") or row.get("significant_bonferroni_alpha_005")
    ]
    checks["signal_diagnostic_result_count"] = len(signal_diagnostics.get("conditional_results", []))
    checks["signal_diagnostic_calibration_count"] = len(signal_diagnostics.get("calibration_results", []))
    checks["signal_diagnostic_corrected_significant_count"] = len(corrected_significant)
    checks["signal_diagnostic_decision"] = signal_diagnostics.get("decision")
    checks["signal_diagnostics_warehouse_hash_match"] = signal_diagnostics.get("dataset", {}).get("warehouse_sha256") == sha256(warehouse)
    checks["signal_diagnostics_assumptions_hash_match"] = signal_diagnostics.get("assumptions_sha256") == current_assumptions_hash
    checks["signal_diagnostics_knowledge_base_hash_match"] = signal_diagnostics.get("knowledge_base_sha256") == current_knowledge_base_hash
    current_signal_code_hash = current_hash(project_root, "research/signal_diagnostics.py")
    checks["signal_diagnostics_code_hash_match"] = signal_diagnostics.get("code_sha256") == current_signal_code_hash
    if not checks["signal_diagnostics_warehouse_hash_match"] or not checks["signal_diagnostics_assumptions_hash_match"] or not checks["signal_diagnostics_knowledge_base_hash_match"] or not checks["signal_diagnostics_code_hash_match"]:
        blockers.append("signal diagnostics provenance hashes do not match current inputs")
    if signal_diagnostics.get("decision") != "NO_DEPLOYMENT_CANDIDATE":
        blockers.append("signal diagnostics did not return a no-candidate deployment status")
    corrected_significant_oos = [
        row for row in corrected_significant
        if row.get("split") in {"validation_2022", "test_2023", "test_2024", "current_2025_present"}
    ]
    corrected_significant_train = [row for row in corrected_significant if row.get("split") == "research_train"]
    checks["signal_diagnostic_corrected_significant_oos_count"] = len(corrected_significant_oos)
    checks["signal_diagnostic_corrected_significant_train_count"] = len(corrected_significant_train)
    if corrected_significant_oos:
        blockers.append("corrected signal findings require independent replication and execution validation before any deployment")
    elif corrected_significant_train:
        reasons.append("corrected signal findings occurred only in research_train and did not replicate out of sample")
    else:
        reasons.append("no volume/price finding survived the recorded multiple-testing thresholds")

    checks["historical_orderbook_available"] = False
    checks["historical_trade_stream_available"] = False
    blockers.append("historical bid/ask, trades, and order-book data are absent; microstructure execution cannot be validated")
    blockers.append("exchange-specific fees, minimums, and live connector documentation are not yet verified for deployment")
    blockers.append("independent paper-trading validation and calibration are not complete")

    artifact_hashes = {
        "warehouse": sha256(warehouse),
        "baseline": sha256(baseline_path),
        "analysis": sha256(analysis_path),
        "walk_forward": sha256(walk_forward_path),
        "viability": sha256(viability_path),
        "risk_review": sha256(risk_review_path),
        "signal_diagnostics": sha256(signal_diagnostics_path),
    }
    return {
        "report_version": "deployment-gate-v1",
        "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "stage": "Stage 0/1 research and backtest; not paper-trading or live deployment",
        "checks": checks,
        "artifact_hashes": artifact_hashes,
        "reasons_for_abstention": reasons,
        "blockers": sorted(set(blockers)),
        "decision": "ABSTAIN_NO_LIVE_TRADING",
        "deployment_status": "blocked",
        "required_next_stages": [
            "Acquire and validate historical trades, best bid/ask, and order-book updates.",
            "Replace OHLCV execution proxies with exchange-specific fee, spread, slippage, latency, and fill models.",
            "Run predeclared feature/target experiments with multiple-testing controls and confidence intervals.",
            "Perform live-data paper trading with probability calibration and drift monitoring.",
            "Verify official Quidax/Luno APIs and use read/trade-only credentials before any authorized minimal-capital test.",
        ],
        "human_kill_switch_required": True,
        "leverage_authorized": False,
    }


def main() -> int:
    args = parse_args()
    try:
        report = run(args)
        output = args.output.expanduser().resolve()
        output.parent.mkdir(parents=True, exist_ok=True)
        temporary = output.with_name(f".{output.name}.{uuid.uuid4().hex}.part")
        try:
            temporary.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
            os.replace(temporary, output)
        finally:
            temporary.unlink(missing_ok=True)
        print(f"wrote {output}")
        return 0
    except Exception as exc:
        print(f"deployment gate failed: {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
